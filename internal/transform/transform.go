// Package transform rewrites authored Pesto test files into standard Go tests.
//
// Each authored `func TestX(t *pesto.T)` is renamed, by a byte-precise edit, to an
// unexported body function so line numbers are preserved, and a companion wrappers
// file is generated with the real `func TestX(t *testing.T)` that calls
// pesto.Run. Both are fed to the compiler via `go test -overlay`; nothing on disk
// is modified. See docs/design/active/design-test-context.md.
package transform

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"sort"
	"strings"
)

// RuntimeImportPath is the module whose T type marks a function as a Pesto test.
const RuntimeImportPath = "github.com/bulkashmak/pesto"

// bodyPrefix is prepended to an authored test's name to form its body function.
const bodyPrefix = "pestoBody_"

// GeneratedFileName is the base name of the wrappers file added to each package.
const GeneratedFileName = "pesto_generated_test.go"

// TestFunc is a Pesto test discovered in a file.
type TestFunc struct {
	Name string
}

// FileResult is the outcome of rewriting a single authored test file.
type FileResult struct {
	Package   string     // the file's package name
	Tests     []TestFunc // Pesto tests found (empty if none)
	Rewritten []byte     // rewritten source (nil if no Pesto tests)
}

// RewriteFile parses an authored test file and, if it contains Pesto tests,
// returns its rewritten source (test functions renamed to bodies, with a //line
// directive so diagnostics point back at absPath) plus the tests found. Files with
// no Pesto tests return a result with an empty Tests slice and nil Rewritten.
func RewriteFile(absPath string, src []byte) (*FileResult, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, absPath, src, parser.ParseComments)
	if err != nil {
		return nil, fmt.Errorf("parse %s: %w", absPath, err)
	}

	local, ok := pestoLocalName(f)
	if !ok {
		return &FileResult{Package: f.Name.Name}, nil
	}

	type rename struct {
		start, end int
		name       string
	}
	var renames []rename
	var tests []TestFunc

	for _, decl := range f.Decls {
		fd, ok := decl.(*ast.FuncDecl)
		if !ok || fd.Recv != nil {
			continue
		}
		if !strings.HasPrefix(fd.Name.Name, "Test") || !isPestoParam(fd.Type, local) {
			continue
		}
		tests = append(tests, TestFunc{Name: fd.Name.Name})
		renames = append(renames, rename{
			start: fset.Position(fd.Name.Pos()).Offset,
			end:   fset.Position(fd.Name.End()).Offset,
			name:  bodyPrefix + fd.Name.Name,
		})
	}

	if len(tests) == 0 {
		return &FileResult{Package: f.Name.Name}, nil
	}

	// Apply renames from last to first so earlier offsets stay valid.
	sort.Slice(renames, func(i, j int) bool { return renames[i].start > renames[j].start })
	out := append([]byte(nil), src...)
	for _, r := range renames {
		var nb []byte
		nb = append(nb, out[:r.start]...)
		nb = append(nb, r.name...)
		nb = append(nb, out[r.end:]...)
		out = nb
	}

	var buf bytes.Buffer
	// The directive is physical line 1; it declares the *next* physical line to be
	// authored line 1, restoring the original numbering despite the prepended line.
	fmt.Fprintf(&buf, "//line %s:1\n", absPath)
	buf.Write(out)

	return &FileResult{Package: f.Name.Name, Tests: tests, Rewritten: buf.Bytes()}, nil
}

// WrappersFile builds the generated wrappers file for a package: one standard
// `func TestX(t *testing.T)` per Pesto test, delegating to pesto.Run.
func WrappersFile(pkg string, tests []TestFunc) ([]byte, error) {
	sorted := append([]TestFunc(nil), tests...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })

	var buf bytes.Buffer
	buf.WriteString("// Code generated by pesto; DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkg)
	buf.WriteString("import (\n\t\"testing\"\n\n\tpesto \"" + RuntimeImportPath + "\"\n)\n\n")
	for _, tf := range sorted {
		fmt.Fprintf(&buf, "func %s(t *testing.T) { pesto.Run(t, %s%s) }\n", tf.Name, bodyPrefix, tf.Name)
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated wrappers: %w", err)
	}
	return formatted, nil
}

// pestoLocalName returns the local name the file imports the runtime under. A
// blank or dot import disqualifies the file (its tests cannot be identified).
func pestoLocalName(f *ast.File) (string, bool) {
	for _, imp := range f.Imports {
		if strings.Trim(imp.Path.Value, `"`) != RuntimeImportPath {
			continue
		}
		if imp.Name != nil {
			if imp.Name.Name == "_" || imp.Name.Name == "." {
				return "", false
			}
			return imp.Name.Name, true
		}
		return "pesto", true
	}
	return "", false
}

// isPestoParam reports whether ft is `(t *<local>.T)`.
func isPestoParam(ft *ast.FuncType, local string) bool {
	if ft.Params == nil || len(ft.Params.List) != 1 {
		return false
	}
	star, ok := ft.Params.List[0].Type.(*ast.StarExpr)
	if !ok {
		return false
	}
	sel, ok := star.X.(*ast.SelectorExpr)
	if !ok {
		return false
	}
	x, ok := sel.X.(*ast.Ident)
	return ok && x.Name == local && sel.Sel.Name == "T"
}
